def strip_ko_suffix(word: str) -> str:
    """한국어 단어에서 조사·어미를 제거해 어근을 반환한다.

    접미사가 인식되지만 어근이 2글자 미만이면 빈 문자열을 반환해 해당 단어를 건너뛴다.
    """
    for suffix in _KO_SUFFIXES:
        if word.endswith(suffix):
            stem = word[: -len(suffix)]
            return stem if len(stem) >= 2 else ""
    return word


def extract_keywords(text: str) -> list[str]:
    """텍스트에서 의미 있는 키워드를 추출한다."""
    words = re.findall(r'[가-힣]{2,}|[A-Za-z]{3,}', text)
    seen: set[str] = set()
    result: list[str] = []
    for w in words:
        if re.match(r'^[가-힣]+$', w):
            w = strip_ko_suffix(w)
        else:
            w = w.lower()
        if len(w) < 2:
            continue
        if w not in STOPWORDS and w not in seen:
            seen.add(w)
            result.append(w)
    return result
